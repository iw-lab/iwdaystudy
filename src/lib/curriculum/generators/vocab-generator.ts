// Main export
// ============================================================

export function generateVocabPool(
  grade: number,
  seed: number,
  difficulty: 1 | 2 | 3 = 2,
): VocabEntry[] {
  const rng = seededRandom(seed);

  let baseWords: WordDef[];
  let extraWords: WordDef[] = [];

  if (grade <= 2) {
    baseWords = [...GRADE_1_2_WORDS];
  } else if (grade <= 4) {
    baseWords = [...GRADE_1_2_WORDS, ...GRADE_3_4_WORDS];
    extraWords = [...COMPOUNDS_3_4];
  } else {
    baseWords = [...GRADE_3_4_WORDS, ...GRADE_5_6_WORDS];
    extraWords = [...COMPOUNDS_3_4, ...ABSTRACT_5_6];
  }

  // Combine and deduplicate
  let allWords = deduplicateByWord([...baseWords, ...extraWords]);

  // Apply difficulty filtering
  if (difficulty !== 2 && allWords.length > 10) {
    const cutoff40 = Math.ceil(allWords.length * 0.4);
    if (difficulty === 1) {
      // Easy: first 40% of word list (common words with simpler meanings)
      allWords = allWords.slice(0, cutoff40);
    } else {
      // Hard: last 40% (abstract words) + filter for words with 2+ meanings
      const hardSlice = allWords.slice(allWords.length - cutoff40);
      const multiMeaning = allWords.filter((w) => w.meanings.length >= 2);
      // Merge hard slice with multi-meaning words, deduplicate
      allWords = deduplicateByWord([...hardSlice, ...multiMeaning]);
    }
  }

  // Shuffle with seed
  shuffleArray(allWords, rng);

  // If pool is empty after filtering, return empty
  if (allWords.length === 0) return [];

  // Ensure we have at least 500 entries by cycling the pool
  const target = 500;
  if (allWords.length < target) {
    const pool = [...allWords];
    let idx = 0;
    while (allWords.length < target) {
      allWords.push(pool[idx % pool.length]);
      idx++;
    }
  }

  // Take exactly 500
  const selected = allWords.slice(0, target);

  // Final shuffle
  shuffleArray(selected, rng);

  // Convert to VocabEntry format
  return selected.map((w) => ({
    meanings: w.meanings,
    answer: w.word,
  }));
}

