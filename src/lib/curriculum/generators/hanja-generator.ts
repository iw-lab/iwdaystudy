/**
 * Generates a pool of Hanja entries appropriate for the given grade level.
 *
 * @param grade - Student grade (1-6). Grades 1-2 return empty array.
 * @param seed - Seed for the PRNG to ensure reproducible results.
 * @returns Array of 300 HanjaEntry items (or empty for grades 1-2).
 */
export function generateHanjaPool(
  grade: number,
  seed: number,
  difficulty: 1 | 2 | 3 = 2,
): HanjaEntry[] {
  // Grades 1-2 do not study Hanja
  if (grade <= 2) {
    return [];
  }

  const rng = seededRandom(seed);

  let pool: HanjaData[];

  if (grade <= 4) {
    // Grade 3-4: Basic Hanja (급수 8-7급)
    pool = [...GRADE_3_4_HANJA, ...EXTRA_34];
  } else {
    // Grade 5-6: Intermediate Hanja (급수 6-5급) + some basic for review
    pool = [...GRADE_5_6_HANJA, ...EXTRA_56, ...GRADE_3_4_HANJA, ...EXTRA_34];
  }

  // Filter by difficulty based on stroke count
  if (difficulty === 1) {
    // Easy: characters with ≤6 strokes (simpler characters)
    const filtered = pool.filter((h) => h.strokes <= 6);
    if (filtered.length > 0) pool = filtered;
  } else if (difficulty === 3) {
    // Hard: characters with >8 strokes (complex characters)
    const filtered = pool.filter((h) => h.strokes > 8);
    if (filtered.length > 0) pool = filtered;
  }
  // difficulty === 2: no filtering (current behavior)

  // Shuffle with seeded PRNG
  const shuffled = shuffle(pool, rng);

  if (shuffled.length === 0) return [];

  // Return exactly 300 items (cycling if necessary to fill)
  const TARGET_COUNT = 300;
  const result: HanjaEntry[] = [];

  for (let i = 0; i < TARGET_COUNT; i++) {
    const entry = shuffled[i % shuffled.length];
    const fix = HANJA_FIX[entry.character];
    result.push({
      character: entry.character,
      reading: fix?.reading ?? entry.reading,
      meaning: fix?.meaning ?? entry.meaning,
      strokes: fix?.strokes ?? entry.strokes,
      words: fix?.words ? [...fix.words] : [...entry.words],
      sentence: fix?.sentence ?? entry.sentence,
    });
  }

  return result;
}
